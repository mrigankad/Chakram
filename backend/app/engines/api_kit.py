def app_store_ts(spec: AppSpec) -> str:
    names = list(spec.entities)
    cols = {n: collection_name(n) for n in names}
    out = [
        "/* App data: the seed rows, or the live API when VITE_API_URL is set. Generated by Chakram. */",
        "import { useSyncExternalStore } from 'react';",
        f"import type {{ {', '.join(names)} }} from './types';",
        "import { seed } from './seed';",
        "",
        "export type AppData = {",
        "  ready: boolean;",
        "  source: 'seed' | 'api';",
        "  error: string | null;",
    ]
    for n in names:
        out.append(f"  {cols[n]}: {n}[];")
    out += [
        "};",
        "",
        "const API_URL = ((import.meta as unknown as { env?: Record<string, string | undefined> }).env?.VITE_API_URL ?? '').replace(/\\/$/, '');",
        "",
        "const collections = {",
    ]
    for n in names:
        out.append(f"  {n}: {json.dumps(cols[n])},")
    out += [
        "} as const;",
        "",
        "function fromSeed(): AppData {",
        "  return {",
        "    ready: true,",
        "    source: 'seed',",
        "    error: null,",
    ]
    for n in names:
        out.append(f"    {cols[n]}: seed.{n},")
    out += [
        "  };",
        "}",
        "",
        "let state: AppData = API_URL",
        "  ? { ...fromSeed(), ready: false, source: 'api' }",
        "  : fromSeed();",
        "const listeners = new Set<() => void>();",
        "let started = false;",
        "",
        "function setState(next: AppData): void {",
        "  state = next;",
        "  listeners.forEach((l) => l());",
        "}",
        "",
        "export async function request<T>(path: string, init?: RequestInit): Promise<T> {",
        "  const res = await fetch(`${API_URL}${path}`, { credentials: 'include', headers: { 'content-type': 'application/json' }, ...init });",
        "  if (res.status === 204) return undefined as T;",
        "  const body = (await res.json().catch(() => null)) as T & { message?: string };",
        "  if (!res.ok) throw new Error((body && body.message) || `${res.status} ${res.statusText}`);",
        "  return body;",
        "}",
        "",
        "export async function reload(): Promise<void> {",
        "  if (!API_URL) return;",
        "  try {",
        "    const [",
        ", ".join(f"{cols[n]}" for n in names),
        "    ] = await Promise.all([",
    ]
    for n in names:
        out.append(f"      request<{{ rows: {n}[] }}>('/api/{cols[n]}?limit=500').then((r) => r.rows),")
    out += [
        "    ]);",
        "    setState({ ready: true, source: 'api', error: null, " + ", ".join(cols[n] for n in names) + " });",
        "  } catch (err) {",
        "    setState({ ...state, ready: true, error: err instanceof Error ? err.message : String(err) });",
        "  }",
        "}",
        "",
        "/** Every collection of the app. Reads the seed until VITE_API_URL is set; then the API, loaded once. */",
        "export function useAppData(): AppData {",
        "  if (API_URL && !started) {",
        "    started = true;",
        "    void reload();",
        "  }",
        "  return useSyncExternalStore(",
        "    (listener) => {",
        "      listeners.add(listener);",
        "      return () => listeners.delete(listener);",
        "    },",
        "    () => state,",
        "    () => state,",
        "  );",
        "}",
        "",
        "let localSeq = 0;",
        "function localId(prefix: string): string {",
        "  localSeq += 1;",
        "  return `${prefix}-local-${Date.now().toString(36)}-${localSeq}`;",
        "}",
        "",
        "/** Writes. Against the API when VITE_API_URL is set; otherwise in memory (lost on reload, like the seed). */",
        "function writer<T extends { id: string }>(key: keyof typeof collections, collection: string) {",
        "  const list = () => (state as unknown as Record<string, T[]>)[collection];",
        "  const put = (rows: T[]) => setState({ ...state, [collection]: rows });",
        "  return {",
        "    create: async (data: Omit<T, 'id'>): Promise<T> => {",
        "      if (API_URL) {",
        "        const row = await request<T>(`/api/${collection}`, { method: 'POST', body: JSON.stringify(data) });",
        "        await reload();",
        "        return row;",
        "      }",
        "      const row = { ...data, id: localId(String(key).toLowerCase()) } as T;",
        "      put([row, ...list()]);",
        "      return row;",
        "    },",
        "    update: async (id: string, data: Partial<Omit<T, 'id'>>): Promise<T> => {",
        "      if (API_URL) {",
        "        const row = await request<T>(`/api/${collection}/${id}`, { method: 'PUT', body: JSON.stringify(data) });",
        "        await reload();",
        "        return row;",
        "      }",
        "      const rows = list().map((r) => (r.id === id ? ({ ...r, ...data } as T) : r));",
        "      put(rows);",
        "      const row = rows.find((r) => r.id === id);",
        "      if (!row) throw new Error(`${String(key)} ${id} not found`);",
        "      return row;",
        "    },",
        "    remove: async (id: string): Promise<void> => {",
        "      if (API_URL) {",
        "        await request<void>(`/api/${collection}/${id}`, { method: 'DELETE' });",
        "        await reload();",
        "        return;",
        "      }",
        "      put(list().filter((r) => r.id !== id));",
        "    },",
        "  };",
        "}",
        "",
        "export const api = {",
    ]
    for n in names:
        out.append(f"  {cols[n]}: writer<{n}>({json.dumps(n)}, {json.dumps(cols[n])}),")
    out += ["};", "", "export const collectionNames = collections;", ""]
    return "\n".join(out)


