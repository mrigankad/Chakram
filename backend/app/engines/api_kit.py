def readme_md(spec: AppSpec) -> str:
    lines = [
        f"# {spec.name} API",
        "",
        "Generated by Chakram from `app.spec.json`. The API shape is the same for every Chakram app; only the entities differ.",
        "",
        "## Run",
        "",
        "```bash",
        "cd api && npm install",
        "cp .env.example .env            # set DATABASE_URL for PostgreSQL, or leave it empty for the in-memory store",
        "psql \"$DATABASE_URL\" -f migrations/0001_init.sql   # PostgreSQL only",
        "npm run dev                     # http://localhost:3001",
        "```",
        "",
        "On first start the API creates the owner account from `SEED_OWNER_EMAIL` / `SEED_OWNER_PASSWORD` and loads `src/seed.json` when the tables are empty.",
        "",
        "Point the app at it with `VITE_API_URL=http://localhost:3001` (see `src/data/store.ts`).",
        "",
        "## Routes",
        "",
        "| Method | Path | Role |",
        "| --- | --- | --- |",
        "| GET | `/api/health`, `/api/ready` | — |",
        "| POST | `/api/auth/signup`, `/api/auth/login`, `/api/auth/logout` | — |",
        "| GET | `/api/auth/me` | viewer |",
        "| PUT | `/api/auth/users/:id/role` | owner |",
    ]
    for name in spec.entities:
        col = collection_name(name)
        lines.append(f"| GET | `/api/{col}` (`?sort=&dir=&limit=&offset=&<field>=`) and `/api/{col}/:id` | viewer |")
        lines.append(f"| POST / PUT / DELETE | `/api/{col}`, `/api/{col}/:id` | member |")
    lines += [
        "",
        "Every row belongs to the signed-in user's org; another org's rows are never listed, read, changed or deleted. Validation comes from `src/schema.ts` (zod); refs must point at existing rows. Errors are `{ code, message, retryable, fields? }`.",
        "",
        "## Migrations",
        "",
        "`migrations/0001_init.sql` creates users, sessions, orgs and one table per entity. Add a new numbered file for every schema change and keep changes additive (add a column with a default, backfill, then remove the old one in a later file).",
        "",
        "## Deploy",
        "",
        "Any Node 20+ host runs `npm run build && npm start`. For Vercel, wrap `app` from `src/index.ts` with `@hono/vercel` in an `api/index.ts` function and set `DATABASE_URL`, `SESSION_SECRET` and the seed variables as project environment variables.",
        "",
    ]
    return "\n".join(lines)


