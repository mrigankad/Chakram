    return {
        "api/package.json": package_json(spec),
        "api/tsconfig.json": TSCONFIG,
        "api/.env.example": ENV_EXAMPLE,
        "api/README.md": readme_md(spec),
        "api/migrations/0001_init.sql": migration_sql(spec),
        "api/src/schema.ts": schema_ts(spec),
        "api/src/store.ts": STORE_TS,
        "api/src/auth.ts": AUTH_TS,
        "api/src/routes.ts": ROUTES_TS,
        "api/src/index.ts": INDEX_TS.replace("'__APP_FIRST_ENTITY__'", _q(first)),
        "api/src/seed.ts": SEED_TS,
        "api/src/seed.json": json.dumps({n: [{k: v for k, v in r.items() if k != "id"} | {"id": r["id"]} for r in rows] for n, rows in seed_rows.items()}, ensure_ascii=False, indent=2) + "\n",
    }
