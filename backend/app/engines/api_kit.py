def _sql_type(field: FieldSpec) -> str:
    if field.kind in ("number", "money", "percent"):
        return "double precision"
    if field.kind == "boolean":
        return "boolean"
    if field.kind == "date":
        return "date"
    if field.kind == "datetime":
        return "timestamptz"
    return "text"


def migration_sql(spec: AppSpec) -> str:
    out = [
        "-- 0001_init: generated by Chakram from app.spec.json. Additive changes go in new numbered files.",
        "create table if not exists orgs (",
        "  id text primary key,",
        "  name text not null,",
        "  created_at timestamptz not null default now()",
        ");",
        "create table if not exists users (",
        "  id text primary key,",
        "  org_id text not null references orgs(id),",
        "  email text not null unique,",
        "  name text not null,",
        "  password_hash text not null,",
        "  role text not null check (role in ('owner', 'member', 'viewer')),",
        "  created_at timestamptz not null default now()",
        ");",
        "create table if not exists sessions (",
        "  token text primary key,",
        "  user_id text not null references users(id) on delete cascade,",
        "  expires_at timestamptz not null",
        ");",
        "create index if not exists sessions_user_idx on sessions(user_id);",
        "",
    ]
    for name, entity in spec.entities.items():
        table = _table(name)
        out.append(f"create table if not exists {table} (")
        out.append("  id text primary key,")
        out.append("  org_id text not null references orgs(id),")
        for fname, field in entity.fields.items():
            if fname == "id":
                continue
            check = ""
            if field.kind == "enum":
                check = f" check ({_column(fname)} in ({', '.join(json.dumps(v).replace(chr(34), chr(39)) for v in field.values)}))"
            out.append(f"  {_column(fname)} {_sql_type(field)} not null{check},")
        out.append("  created_at timestamptz not null default now(),")
        out.append("  updated_at timestamptz not null default now()")
        out.append(");")
        out.append(f"create index if not exists {table}_org_idx on {table}(org_id);")
        for fname, field in entity.fields.items():
            if field.kind == "ref":
                out.append(f"create index if not exists {table}_{_column(fname)}_idx on {table}({_column(fname)});")
        out.append("")
    return "\n".join(out) + "\n"


