"""API kit: the backend of a composed app, generated from its entities.

The shape never comes from the model. For every spec the kit is the same
TypeScript service (Hono + zod + PostgreSQL) with:

    api/src/schema.ts        zod schemas and types per entity (from the spec)
    api/src/store.ts         Store interface; PgStore (postgres) and MemoryStore (dev)
    api/src/auth.ts          scrypt passwords, session cookie, roles owner/member/viewer
    api/src/routes.ts        list/get/create/update/delete per entity, org-scoped, validated
    api/src/index.ts         the app and the Node server; /api/health, /api/auth/*
    api/src/seed.ts          loads api/src/seed.json into an empty store
    api/migrations/0001_init.sql   users, sessions, one table per entity, indexes
    api/package.json, tsconfig.json, .env.example, README.md

The app side gets `src/data/store.ts`: `useAppData()` returns every collection
from the seed, or from the API when VITE_API_URL is set, plus a typed client
for writes. Composed pages read through that hook, so the preview (no API)
and the exported app (real API) run the same page code.
"""
