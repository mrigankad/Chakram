"""Composer: renders an `AppSpec` into app files from the Chronos kit, deterministically.

For a spec the composer writes:

    src/data/types.ts     one interface per entity, enum unions
    src/data/queries.ts   generic helpers (count/sum/avg, series, top, lookup); fixed text
    src/data/seed.ts      the seed rows (validated model output, or a plain fallback)
    src/pages/<Page>.tsx  one file per page, composed from its blocks
    app.spec.json         the spec itself, for later edits

No model call is involved for any of these. The only model-written files in
a composed app are the seed rows (JSON, validated here) and the bodies of
`custom` blocks (generated and verified like any file).
"""
from __future__ import annotations

import json
import re
from datetime import date, timedelta
from typing import Any

from app.engines.spec import AppSpec, Block, EntitySpec, FieldSpec, Metric, PageSpec

# ── naming ──────────────────────────────────────────────────────────────────

def collection_name(entity: str) -> str:
    """'Appointment' -> 'appointments', 'Category' -> 'categories', 'Status' -> 'statuses'."""
    name = entity[0].lower() + entity[1:]
    if re.search(r"[^aeiou]y$", name):
        return name[:-1] + "ies"
    if name.endswith(("s", "x", "z", "ch", "sh")):
        return name + "es"
    return name + "s"


def _ts_type(field: FieldSpec, entity: str, fname: str) -> str:
    if field.kind in ("number", "money", "percent"):
        return "number"
    if field.kind == "boolean":
        return "boolean"
    if field.kind == "enum":
        return f"{entity}{fname[:1].upper()}{fname[1:]}"
    return "string"


def _q(text: str) -> str:
    """A TS string literal."""
    return json.dumps(text, ensure_ascii=False)


